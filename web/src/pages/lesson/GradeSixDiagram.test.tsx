import { cleanup, fireEvent, render, screen } from "@testing-library/react";
import { afterEach, expect, it } from "vitest";
import { GradeSixDiagram } from "./GradeSixDiagram";
import type { SixVisual } from "../../lesson/grade-six-types";

afterEach(cleanup);
it("3/5÷3は5等分のまま3人に配り、1人分を強調する", () => {
  const visual: SixVisual = {kind:"six",type:"fraction",a:[3,5],b:[3,1],operation:"divide"};
  const {container}=render(<GradeSixDiagram visual={visual} step={0} />);
  expect(container.querySelectorAll(".six__juice-piece")).toHaveLength(3);
  expect(container.querySelectorAll(".six__outline")).toHaveLength(5);
  expect(container.querySelector(".six__share-focus")).toBeNull();
  for(let person=1;person<=3;person++) fireEvent.click(screen.getByRole("button",{name:`${person}人目に配る`}));
  const pieces=[...container.querySelectorAll<SVGElement>(".six__juice-piece")];
  expect(pieces.map(piece=>piece.style.transform)).toEqual(["translate(0px, 102px)","translate(-60px, 187px)","translate(-120px, 272px)"]);
  expect(container.querySelector(".six__share-focus")?.getAttribute("width")).toBe("66");
  expect(screen.getByText("1人目：この1人分を答えよう")).toBeTruthy();
  expect(screen.queryByText("9/15")).toBeNull();
  fireEvent.click(screen.getByRole("button",{name:"はじめから"}));
  expect(container.querySelector(".six__share-focus")).toBeNull();
});
it("3/4÷1/2は4等分で示し、1杯分と残りを順に移す", () => {
  const visual: SixVisual = { kind: "six", type: "fraction", a: [3, 4], b: [1, 2], operation: "divide" };
  const { container, rerender } = render(<GradeSixDiagram visual={visual} step={0} />);
  expect(screen.getByText("全体の1L（同じ大きさに4等分）")).toBeTruthy();
  expect(screen.queryByText("2杯目")).toBeNull();
  const pieces = [...container.querySelectorAll<SVGElement>(".six__juice-piece")];
  const initialTransforms = pieces.map(piece=>piece.style.transform);
  expect(pieces).toHaveLength(3);
  fireEvent.click(screen.getByRole("button", { name: "1杯分を移す" }));
  rerender(<GradeSixDiagram visual={visual} step={1} />);
  expect(pieces.filter(piece=>piece.style.transform.includes("130px"))).toHaveLength(2);
  expect(screen.getByText("2杯目")).toBeTruthy();
  fireEvent.click(screen.getByRole("button", { name: "残りを次のコップへ" }));
  expect(pieces[2].style.transform).toBe("translate(24px, 130px)");
  expect(screen.getByText(/最後のわくに注目/)).toBeTruthy();
  expect(screen.queryByText("3/2")).toBeNull();
  fireEvent.click(screen.getByRole("button", { name: "式で解く方法を見る" }));
  expect(screen.getByText(/分子と分母を入れ替えた数を「逆数」/)).toBeTruthy();
  fireEvent.click(screen.getByRole("button", { name: "次の式" }));
  expect(screen.getByText(/両方に、同じ数をかけても答えは変わりません/)).toBeTruthy();
  fireEvent.click(screen.getByRole("button", { name: "次の式" }));
  expect(screen.getByText(/「分数でわる」を「その逆数をかける」/)).toBeTruthy();
  fireEvent.click(screen.getByRole("button", { name: "次の式" }));
  expect(screen.getByText("3 × 2")).toBeTruthy();
  expect(screen.getByText("4 × 1")).toBeTruthy();
  expect(screen.getAllByText("？")).toHaveLength(2);
  fireEvent.click(screen.getByRole("button", { name: "図にもどる" }));
  const returnedPieces = [...container.querySelectorAll<SVGElement>(".six__juice-piece")];
  fireEvent.click(screen.getByRole("button", { name: "1つもどす" }));
  expect(returnedPieces[2].style.transform).toBe(initialTransforms[2]);
  fireEvent.click(screen.getByRole("button", { name: "はじめから" }));
  expect(returnedPieces.map(piece=>piece.style.transform)).toEqual(initialTransforms);
});
it("2/5の3つ分は、見本を重複させず3つだけ表示する", () => {
  const visual: SixVisual = { kind: "six", type: "fraction", a: [2, 5], b: [3, 1], operation: "multiply" };
  const view = render(<GradeSixDiagram visual={visual} step={-1} />);
  expect(view.container.querySelectorAll(".six__whole")).toHaveLength(1);
  view.rerender(<GradeSixDiagram visual={visual} step={0} />);
  expect(view.container.querySelectorAll(".six__whole")).toHaveLength(2);
  view.rerender(<GradeSixDiagram visual={visual} step={1} />);
  expect(view.container.querySelectorAll(".six__whole")).toHaveLength(3);
  expect(screen.getAllByText("1つ目：2/5")).toHaveLength(1);
  expect(screen.getByText("2つ目：2/5")).toBeTruthy();
  expect(screen.getByText("3つ目：2/5")).toBeTruthy();
  expect(view.container.querySelectorAll(".is-filled")).toHaveLength(6);
});
function finishAnimation(element: Element) {
  fireEvent.animationEnd(element);
  // jsdomではReactがWebKit接頭辞つきのイベントを選ぶ場合もある。
  fireEvent(element, new Event("webkitAnimationEnd", { bubbles: true }));
}
it("2/3を2組に分け、続けて1組だけ選び、再生し直せる", () => {
  const visual: SixVisual = { kind: "six", type: "fraction", a: [2, 3], b: [1, 2], operation: "multiply" };
  const { container } = render(<GradeSixDiagram visual={visual} step={0} />);
  expect(container.querySelector(".six__selected-fill")).toBeNull();
  finishAnimation(container.querySelector(".six__fine-labels")!);
  expect(container.querySelectorAll(".six__equal-groups > span")).toHaveLength(2);
  expect(screen.getByText(/1\/2は、同じ大きさに2つに分けたうちの1つ分/)).toBeTruthy();
  finishAnimation(container.querySelector(".six__equal-groups")!);
  const selection = container.querySelector<HTMLElement>(".six__selected-fill")!;
  expect(parseFloat(selection.style.width)).toBeCloseTo(100 / 3);
  expect(container.querySelector(".six__original-fill.is-clearing")).not.toBeNull();
  expect(parseFloat(container.querySelector<HTMLElement>(".six__source-outline")!.style.width)).toBeCloseTo(200 / 3);
  fireEvent.click(screen.getByRole("button", { name: "一時停止" }));
  expect(selection.style.animationPlayState).toBe("paused");
  fireEvent.click(screen.getByRole("button", { name: "続きを見る" }));
  finishAnimation(selection);
  expect(screen.getByText(/赤い部分は、全体を同じ大きさに分けたうちの何個分/)).toBeTruthy();
  expect(screen.getByText("全体の1（6等分）")).toBeTruthy();
  expect(container.querySelector(".six__source-outline")).toBeNull();
  expect(screen.queryByText("2/6")).toBeNull();
  fireEvent.click(screen.getByRole("button", { name: "もう一度見る" }));
  expect(container.querySelector(".six__selected-fill")).toBeNull();
  expect(container.querySelector(".six__original-fill.is-clearing")).toBeNull();
});
it("半分の量を保ち、縦の切れ目を順番に加えて全体を6等分する", () => {
  const visual: SixVisual = { kind: "six", type: "fraction", a: [1, 2], b: [1, 3], operation: "multiply" };
  const view = render(<GradeSixDiagram visual={visual} step={-1} />);
  expect(view.container.querySelectorAll(".six__new-cut")).toHaveLength(0);
  view.rerender(<GradeSixDiagram visual={visual} step={0} />);
  expect(view.container.querySelectorAll(".six__cut-strip")).toHaveLength(1);
  expect((view.container.querySelector(".six__original-fill") as HTMLElement).style.width).toBe("50%");
  expect((view.container.querySelector(".six__old-cut") as HTMLElement).style.left).toBe("50%");
  const cuts = [...view.container.querySelectorAll<HTMLElement>(".six__new-cut")];
  expect(cuts).toHaveLength(4);
  expect(cuts.map(cut => Math.round(parseFloat(cut.style.left)))).toEqual([17, 33, 67, 83]);
  const delays = cuts.map(cut => parseFloat(cut.style.animationDelay));
  expect(delays.every((delay, index) => index === 0 || delay > delays[index - 1])).toBe(true);
  expect([...view.container.querySelectorAll(".six__fine-labels > span")].map(node => node.textContent)).toEqual(["1", "2", "3", "4", "5", "6"]);
  fireEvent.click(screen.getByRole("button", { name: "一時停止" }));
  expect(cuts.every(cut => cut.style.animationPlayState === "paused")).toBe(true);
  fireEvent.click(screen.getByRole("button", { name: "続きを見る" }));
  expect(cuts.every(cut => cut.style.animationPlayState === "running")).toBe(true);
  fireEvent.click(screen.getByRole("button", { name: "もう一度見る" }));
  expect(cuts[0].isConnected).toBe(false);
  expect(view.container.querySelectorAll(".six__new-cut")).toHaveLength(4);
});
